const assert = require('node:assert/strict')
const path = require('node:path')
const { buildSync } = require('esbuild')
const output = buildSync({ entryPoints: [path.join(__dirname, '../src/main/evidence-selection.ts')], bundle: true, platform: 'node', format: 'cjs', write: false })
const entry = { exports: {} }
new Function('module', 'exports', 'require', output.outputFiles[0].text)(entry, entry.exports, require)
const { fuseEvidenceRanks, selectEvidenceClusters, renderEvidenceCluster, researchEvidenceAspects, evidenceExcerpt, EVIDENCE_SOURCE_LIMIT, EVIDENCE_CONTEXT_BYTES } = entry.exports
const source = (doc, snippet, page = 1) => ({ doc_id: doc, doc_title: doc, page_num: page, snippet, locator: { segmentId: `${doc}:${page}`, docId: doc, pageNum: page } })
const cluster = (id, score, text, doc = id) => ({ id, doc_id: doc, doc_title: doc, anchor_page_num: 1, page_range: [1, 3], score, queries: ['讲学'], hit_count: 1,
  sources: [source(doc, text)], pages: [{ page_num: 1, role: 'hit', text }, { page_num: 2, role: 'after', text: '上下文补充。'.repeat(250) }] })

const keyword = { ...source('shared', '原文证据'), rank: -999, relevance_score: 1000 }
const semantic = { ...keyword, rank: -0.7, relevance_score: 0.7 }
const fused = fuseEvidenceRanks([keyword, keyword, { ...source('lexical', '异名精确匹配'), rank: -9999 }], [semantic, { ...source('vector', '换一种说法'), rank: -0.9 }])
assert.equal(fused.length, 3)
assert.equal(fused[0].doc_id, 'shared')
assert(Math.abs(fused[0].relevance_score - 2 / 61) < 1e-10, 'duplicates within a channel must not inflate reciprocal ranks')

const repeated = Array.from({ length: 20 }, (_, i) => cluster(`repeat-${i}`, 1 - i / 100, '甲乙共同讲学于书院。'.repeat(15), 'same-doc'))
const counter = cluster('different-doc', 0.9, '丙的记载否认师承，仅承认共同讲学；证据仍有争议。')
const selected = selectEvidenceClusters([...repeated, counter])
assert(selected.clusters.some((item) => item.id === 'different-doc'), 'relevant dissenting text should survive redundant majority evidence')
assert(selected.sourceCount <= EVIDENCE_SOURCE_LIMIT)
assert(selected.bytes <= EVIDENCE_CONTEXT_BYTES)
const serialized = selected.clusters.map(renderEvidenceCluster).join('\n\n---\n\n')
assert.equal(Buffer.byteLength(serialized, 'utf8'), selected.bytes, 'budget must measure the actual serialized model evidence')
assert(selected.clusters.every((item) => item.sources.length > 0))
assert.equal(selected.sourceCount, 2, 'identical evidence from the same document and page must occupy one primary slot')
const primaryFirst = selectEvidenceClusters(Array.from({ length: 8 }, (_, i) => cluster(`primary-${i}`, 1, `不同证据${i}。`.repeat(20))))
assert.equal(primaryFirst.sourceCount, 8, 'optional page context must not consume the budget before primary evidence is selected')
const sourceText = '甲乙共同讲学于书院。'.repeat(15)
const single = renderEvidenceCluster(cluster('one', 1, sourceText), 0)
assert.equal(single.split(sourceText).length - 1, 1, 'page expansion should not duplicate an already included source excerpt')

const oversized = cluster('oversized', 100, '超长正文'.repeat(10000))
const afterLarge = selectEvidenceClusters([oversized, cluster('small', 1, '短证据仍然可读。')])
assert.deepEqual(afterLarge.clusters.map((item) => item.id), ['small'], 'an oversized first result must not suppress later usable evidence')
assert.equal(selectEvidenceClusters([]).sourceCount, 0)
assert.deepEqual(researchEvidenceAspects('甲乙是否存在师承关系？'), [], 'ordinary factual questions must not inherit a research-method preference')
const aspects = researchEvidenceAspects('研究资料获取、研究方法与材料偏见')
const topics = Array.from({ length: 10 }, (_, i) => cluster(`topic-${i}`, 1 - i / 100, `地方教育发展背景${i}。`, 'book'))
const method = cluster('method', 0.85, '本文采用档案、报纸和深度访谈，比较不同群体的记忆偏向。', 'book')
const focused = selectEvidenceClusters([...topics, method], aspects)
assert.equal(focused.clusters[0].id, 'method', 'a directly relevant method paragraph should outrank repeated topic-only background')
assert(focused.sourceCount <= EVIDENCE_SOURCE_LIMIT && focused.bytes <= EVIDENCE_CONTEXT_BYTES)
const late = '前文背景。'.repeat(1200) + '关键人物在此处出现。' + '后文。'.repeat(500)
assert(evidenceExcerpt(late, ['关键人物'], 900).includes('关键人物'), 'page windows must stay anchored to late-page matches')
assert(!/[\uD800-\uDBFF]$/.test(evidenceExcerpt('😀'.repeat(1000), [], 99).replace(/\.\.\.$/, '')), 'clipping must not split surrogate pairs')

const large = Array.from({ length: 1000 }, (_, i) => cluster(`doc-${i}`, 1 - i / 2000, `文献${i}的独立记载。`.repeat(100)))
const start = performance.now()
const packed = selectEvidenceClusters(large)
assert(packed.sourceCount <= EVIDENCE_SOURCE_LIMIT && packed.bytes <= EVIDENCE_CONTEXT_BYTES)
console.log(`Evidence selection passed: hybrid ranks, duplicate suppression, diversity, source consistency and UTF-8 budget; 1000 candidates in ${(performance.now() - start).toFixed(1)}ms.`)
