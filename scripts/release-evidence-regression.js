const assert = require('assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { execFileSync } = require('child_process')

const root = path.resolve(__dirname, '..')
const output = fs.mkdtempSync(path.join(os.tmpdir(), 'gujismart-release-evidence-'))
try {
  execFileSync(process.execPath, [path.join(root, 'scripts', 'generate-release-evidence.js')], { cwd: root, env: { ...process.env, GUJISMART_RELEASE_EVIDENCE_DIR: output }, stdio: 'pipe' })
  const sbom = JSON.parse(fs.readFileSync(path.join(output, 'sbom.spdx.json'), 'utf8'))
  const vendor = JSON.parse(fs.readFileSync(path.join(output, 'vendor-manifest.json'), 'utf8'))
  const rc = JSON.parse(fs.readFileSync(path.join(output, 'local-rc-manifest.json'), 'utf8'))
  const fixtures = JSON.parse(fs.readFileSync(path.join(root, 'tests', 'fixtures', 'synthetic', 'manifest.json'), 'utf8'))
  assert.strictEqual(sbom.spdxVersion, 'SPDX-2.3')
  assert.ok(sbom.packages.length > 500)
  assert.ok(vendor.files.length > 0)
  assert.ok(vendor.files.every((item) => /^[a-f0-9]{64}$/.test(item.sha256)))
  assert.strictEqual(rc.releaseStatus, 'local-test-pending')
  assert.strictEqual(rc.publicationApproved, false)
  assert.ok(rc.buildFiles.every((item) => /^dist\/[^/]+$/.test(item.path)), 'RC manifest must only include top-level dist artifacts')
  assert.ok(rc.buildFiles.every((item) => !/\.(?:db|pdf)$/i.test(item.path)), 'RC manifest must never include databases or documents')
  const packagedSmoke = fs.readFileSync(path.join(root, 'scripts', 'packaged-smoke.js'), 'utf8')
  assert.ok(packagedSmoke.includes("GUJISMART_DATA_DIR: dataDir"), 'packaged smoke must isolate application data')
  assert.ok(packagedSmoke.includes("GUJISMART_PROFILE_DIR: profileDir"), 'packaged smoke must isolate the Electron profile')
  const releaseWorkflow = fs.readFileSync(path.join(root, '.github', 'workflows', 'release.yml'), 'utf8')
  assert.ok(releaseWorkflow.includes("$tag -notmatch '^v\\d+\\.\\d+\\.\\d+$'"), 'release workflow must require an exact semantic version tag')
  assert.ok(releaseWorkflow.includes('does not match package.json version'), 'release workflow must match the tag to package.json')
  assert.ok(releaseWorkflow.includes("$actual.Count -ne 2"), 'release workflow must require exactly two local exe assets')
  assert.ok(releaseWorkflow.includes('--draft'), 'release workflow must create a draft before uploading assets')
  assert.ok(releaseWorkflow.includes("$remoteAssets.Count -ne 2"), 'release workflow must verify exactly two remote assets')
  assert.ok(releaseWorkflow.includes('Failed to create draft release'), 'release workflow must fail when draft creation fails')
  assert.ok(releaseWorkflow.includes('Failed to publish draft release'), 'release workflow must fail when draft publication fails')
  assert.ok(releaseWorkflow.includes('--draft=false'), 'release workflow must publish only after remote asset verification')
  assert.ok(!releaseWorkflow.includes('--clobber'), 'release workflow must not overwrite immutable public assets')
  assert.deepStrictEqual(fixtures.fixtures.map((item) => item.audience).sort(), ['ancient-text', 'modern-paper'])
  console.log('Release evidence regression passed.')
} finally {
  fs.rmSync(output, { recursive: true, force: true })
}
