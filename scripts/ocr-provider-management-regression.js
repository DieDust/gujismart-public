const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const settingsView = fs.readFileSync(path.join(root, 'src/renderer/src/views/SettingsView.tsx'), 'utf8')
const settingsIpc = fs.readFileSync(path.join(root, 'src/main/ipc/settings.ts'), 'utf8')
const preload = fs.readFileSync(path.join(root, 'src/preload/index.ts'), 'utf8')
const visionOcr = fs.readFileSync(path.join(root, 'src/main/vision-ocr.ts'), 'utf8')

assert.ok(!settingsView.includes("{ id: 'vision_model', label: 'AI OCR 配置'"), 'OCR provider list must not contain a non-deletable legacy placeholder')
assert.ok(settingsView.includes("setSelectedOcrProviderId('vision_draft')"), 'adding AI OCR must create an explicit draft rather than select the legacy engine id')
assert.ok(settingsView.includes("selectedOcrProviderId === 'vision_draft'"), 'AI OCR draft must open the vision editor')
assert.ok(settingsView.includes("{ id: 'vision_draft', label: '新建 AI OCR', desc: '未保存'"), 'adding AI OCR must render a visible unsaved child item')
assert.ok(!settingsIpc.includes("throw new Error('不能删除当前正在使用的视觉 OCR 服务商')"), 'active vision OCR profiles must be deletable with fallback handling')
assert.ok(settingsIpc.includes('remainingProfiles.find((profile) => profile.connectionTest?.verified)'), 'deleting an active vision OCR profile must only select a verified fallback')
assert.ok(settingsIpc.includes("setSettingValue('ocr_default_engine', 'paddle')"), 'deleting the final default vision OCR profile must fall back to cloud PaddleOCR')
assert.ok(settingsView.includes('测试连接'), 'vision OCR editor must provide a connection test command')
assert.ok(settingsView.includes('visionOcrConnectionVerified'), 'vision OCR save and activation controls must track verified connection state')
assert.ok(preload.includes('testVisionOcrProviderConnection'), 'preload must expose an explicit vision OCR connection test API')
assert.ok(settingsIpc.includes("ipcMain.handle('settings:visionOcrProfiles:testConnection'"), 'main settings IPC must perform the connection test')
assert.ok(settingsIpc.includes('assertVisionOcrProfileVerified'), 'saving or activating a vision OCR profile must require a matching successful test')
assert.ok(visionOcr.includes('isCurrentVisionOcrConnectionVerified'), 'runtime vision OCR configuration must require persisted connection verification')

console.log('OCR provider management regression passed.')
