const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), 'utf8')
const assert = (condition, message) => {
  if (!condition) throw new Error(message)
}

const shared = read('src/shared/types.ts')
const preload = read('src/preload/index.ts')
const documents = read('src/main/ipc/documents.ts')
const folders = read('src/main/ipc/folders.ts')
const app = read('src/renderer/src/App.tsx')
const library = read('src/renderer/src/views/LibraryView.tsx')
const foldersView = read('src/renderer/src/views/FoldersView.tsx')
const documentView = read('src/renderer/src/views/DocumentView.tsx')
const settingsView = read('src/renderer/src/views/SettingsView.tsx')

assert(shared.includes('export type CapabilityResult<T>'), 'shared contract must expose a stable CapabilityResult union')
assert(shared.includes('export interface ImportSelection'), 'shared contract must expose opaque import selections')
assert(shared.includes('export interface ImportSelectionBatch'), 'shared contract must expose paginated import batches')
assert(shared.includes("authorizationStatus: 'authorized' | 'authorization-required'"), 'persisted import jobs must expose authorization state')

assert(preload.includes('selectImportSources:'), 'preload must expose main-owned import selection')
assert(preload.includes('grantDroppedImportSources: (files: File[])'), 'preload must convert real dropped File objects internally')
assert(preload.includes('readImportSelectionBatch:'), 'preload must expose paginated selection reads')
assert(preload.includes('releaseImportSelection:'), 'preload must explicitly release completed import selections')
assert(!preload.includes('openFileDialog:'), 'preload must not expose raw file dialog paths')
assert(!preload.includes('getPathForFile:'), 'preload must not expose raw paths for File objects')
assert(!preload.includes('resolveImportSources:'), 'preload must not accept renderer-supplied source paths')
assert(!/importDocuments:\s*\(filePaths:\s*string\[\]/.test(preload), 'preload import must accept grant IDs, not file paths')

assert(documents.includes("ipcMain.handle('documents:selectImportSources'"), 'main must own import dialogs')
assert(documents.includes("ipcMain.handle('documents:grantDroppedImportSources'"), 'main must issue grants for preload-authenticated drops')
assert(documents.includes("ipcMain.handle('documents:readImportSelectionBatch'"), 'main must paginate directory selections')
assert(documents.includes("ipcMain.handle('documents:releaseImportSelection'"), 'main must release completed selection metadata by owner')
assert(!documents.includes("ipcMain.handle('documents:resolveImportSources'"), 'main must remove raw path source resolution')
assert(!documents.includes('allowFileAccessPaths(filePaths)'), 'main import must not promote renderer paths to the display allowlist')
assert(documents.includes('fileCapabilityService.beginFileBatch(')
  && /'document-import',\r?\n\s+IMPORT_FILE_LEASE_TTL_MS/.test(documents), 'main import must atomically lease owner-bound document grants')
assert(!documents.includes('grantIdByPath'), 'main import must not collapse distinct grants through a path-keyed map')
assert(documents.includes('const sourceGrantId = entry.grantId'), 'main import must preserve the lease entry grant ID by index')
assert(documents.includes('renewFileBatch(lease.leaseId'), 'long imports must renew their bounded lease while making progress')

assert(!app.includes('window.api.getPathForFile'), 'App drop handling must not materialize raw paths')
assert(!library.includes('window.api.getPathForFile'), 'Library drop handling must not materialize raw paths')
assert(!library.includes('window.api.resolveImportSources'), 'Library must consume opaque selections')
assert(!foldersView.includes('window.api.getPathForFile'), 'Folders drop handling must not materialize raw paths')
assert(!foldersView.includes('window.api.resolveImportSources'), 'Folders must consume opaque selections')
assert(library.includes('window.api.releaseImportSelection'), 'Library must release completed selection metadata')
assert(foldersView.includes('window.api.releaseImportSelection'), 'Folders must release completed selection metadata')
assert(library.includes('let ownershipTransferred = false') && library.includes('finally {'), 'Library selection workflow must release unless a live queue owns it')
assert(foldersView.includes('let ownershipTransferred = false') && foldersView.includes('finally {'), 'Folders selection workflow must release on every exit path')

assert(!preload.includes('setPdfRepositoryPaths:'), 'renderer must not replace repository paths')
assert(preload.includes('removePdfRepository:'), 'repository removal must use a main-owned repository ID')
assert(preload.includes('selectAndRestorePdfForDocument:'), 'manual PDF restore must be one main-owned dialog operation')
assert(!documentView.includes('restorePdfForDocument(doc.id, manualPath)'), 'manual PDF restore must not pass a path')
assert(!settingsView.includes('setPdfRepositoryPaths'), 'settings must remove repositories by ID')

assert(!preload.includes('scanFolderPath:'), 'renderer must not scan arbitrary directory paths')
assert(!folders.includes("ipcMain.handle('folders:scanPath'"), 'main must remove arbitrary path folder scans')
assert(folders.includes('rejectProtectedExternalPathFields'), 'folder create/update must reject renderer external_path writes')

console.log('Import capability boundary regression passed.')
