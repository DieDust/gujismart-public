        state.calls.push({ question, scope, options })
        const emit = (type, payload) => event.sender.send('ai:streamEvent', { requestId, type, payload })
        emit('phase', '正在查找原文（测试）')
        await new Promise((resolve) => setTimeout(resolve, 1400))
