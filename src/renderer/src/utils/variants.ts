/**
 * 扫描文本中的异体字并返回其位置和建议
 */
export function detectVariants(text: string) {
  const matches: { index: number; original: string; suggestion: string }[] = []
  for (let i = 0; i < text.length; i++) {
    const char = text[i]
    if (VARIANT_MAP[char]) {
      matches.push({
        index: i,
        original: char,
        suggestion: VARIANT_MAP[char]
      })
    }
  }
  return matches
}

/**
 * 一键规范化文本
 */
export function normalizeVariants(text: string): string {
  let result = ''
  for (let i = 0; i < text.length; i++) {
    result += VARIANT_MAP[text[i]] || text[i]
  }
  return result
}
